/**
 * Un personaje volador (gravity 0, ej. manhack) no debe ser pegado al suelo por
 * el `SpawnValidator` al spawnear: conserva la altura de diseño y vuela en el aire.
 */
export function isFlyingCharacter(def: CharacterDefinition): boolean {
  return def.movement.gravity === 0;
}
